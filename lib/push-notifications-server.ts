import type { SupabaseClient } from "@supabase/supabase-js";

export type AppNotificationType =
  | "arena_invite"
  | "arena_member_joined"
  | "match_completed"
  | "season_completed";

type NotificationPreferenceRow = {
  user_id: string;
  arena_invite: boolean;
  arena_member_joined: boolean;
  match_completed: boolean;
  season_completed: boolean;
  push_enabled: boolean;
};

type NotificationInput = {
  type: AppNotificationType;
  content: Record<"it" | "en", { title: string; body: string }>;
  data?: Record<string, string>;
  dedupeKey?: string;
};

export function classifyExpoPushResult(
  result: { status?: string; details?: { error?: string } } | undefined,
) {
  if (result?.status === "ok")
    return { status: "sent" as const, providerCode: null };
  const providerCode = result?.details?.error ?? "UnknownProviderError";
  return {
    status: [
      "DeviceNotRegistered",
      "MessageTooBig",
      "InvalidCredentials",
      "MismatchSenderId",
    ].includes(providerCode)
      ? ("permanent_error" as const)
      : ("retryable_error" as const),
    providerCode,
  };
}

export async function notifyUsers(
  admin: SupabaseClient,
  userIds: string[],
  notification: NotificationInput,
  options: { persist?: boolean } = {},
) {
  const recipients = Array.from(new Set(userIds)).filter(Boolean);
  if (!recipients.length) return;

  // Missing preference rows mean opt-in. If an older V8 schema does not have
  // the table yet, preserve the previous behavior instead of dropping alerts.
  const preferenceResult = await admin
    .from("notification_preferences")
    .select(
      "user_id, arena_invite, arena_member_joined, match_completed, season_completed, push_enabled",
    )
    .in("user_id", recipients);
  const preferences = preferenceResult.error
    ? new Map<string, NotificationPreferenceRow>()
    : new Map(
        ((preferenceResult.data ?? []) as NotificationPreferenceRow[]).map(
          (row) => [row.user_id, row],
        ),
      );
  const inboxRecipients = recipients.filter(
    (userId) => preferences.get(userId)?.[notification.type] !== false,
  );
  if (!inboxRecipients.length) return;

  const localizedData = {
    ...(notification.data ?? {}),
    title_it: notification.content.it.title,
    body_it: notification.content.it.body,
    title_en: notification.content.en.title,
    body_en: notification.content.en.body,
  };
  const rows = inboxRecipients.map((userId) => ({
    user_id: userId,
    type: notification.type,
    title: notification.content.it.title,
    body: notification.content.it.body,
    data: localizedData,
    dedupe_key: notification.dedupeKey
      ? `${notification.dedupeKey}:${userId}`
      : null,
  }));
  let pushRecipients = inboxRecipients;
  if (options.persist !== false) {
    const inserted = notification.dedupeKey
      ? await admin
          .from("app_notifications")
          .upsert(rows, { onConflict: "dedupe_key", ignoreDuplicates: true })
          .select("user_id")
      : await admin.from("app_notifications").insert(rows);
    if (inserted.error) {
      console.error("[notifications] inbox insert failed", {
        code: inserted.error.code,
      });
      return;
    }
    if (notification.dedupeKey) {
      pushRecipients = (
        (inserted.data ?? []) as Array<{ user_id: string }>
      ).map((row) => row.user_id);
      if (!pushRecipients.length) return;
    }
  }

  // The inbox INSERT trigger queues existing devices transactionally, including
  // notifications generated by SQL triggers. The worker owns all delivery retries.
}
