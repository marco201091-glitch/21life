import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const read = (path) => readFileSync(join(root, path), 'utf8');
const failures = [];

const appConfig = read('expo/app.config.js');
const androidLogin = read('expo/app/(auth)/login.tsx');
const sentryRuntime = read('expo/lib/sentry.ts');
const env = read('expo/lib/env.ts');
const fdroidReleasePlugin = read('expo/plugins/with-fdroid-release-build.js');
const fdroidPermissionsPlugin = read('expo/plugins/with-fdroid-blocked-permissions.js');
const fdroidDocs = read('docs/FDROID_RELEASE_READINESS.md');
const metadata = read('fastlane/metadata/android/en-US/full_description.txt');
const fdroidMetadata = read('fdroid/metadata/com.phyrexianarena.app.yml');
const mobilePackage = JSON.parse(read('expo/package.json'));
const mobileVersion = JSON.parse(read('expo/app.json')).expo;
if (!mobilePackage.expo?.autolinking?.android?.buildFromSource?.includes('.*')) {
  failures.push('Every Expo Android module must build from source');
}
if ((fdroidMetadata.match(/versionName:/g) ?? []).length !== 1) {
  failures.push('Initial F-Droid submission must contain only the latest build');
}
if (!fdroidMetadata.includes('    scandelete:\n      - node_modules\n      - expo/node_modules')) {
  failures.push('F-Droid source scanner must delete dependency binaries before building');
}
if (fdroidMetadata.includes('\r') || /[ \t]+$/m.test(fdroidMetadata)) {
  failures.push('F-Droid metadata must use LF without trailing whitespace');
}

if (appConfig.includes('@sentry/react-native/expo')) {
  failures.push('F-Droid branch must not include the Sentry Expo plugin');
}
if (!appConfig.includes("'./plugins/with-fdroid-release-build'")) {
  failures.push('F-Droid branch must include the F-Droid release build plugin');
}
if (!appConfig.includes("'./plugins/with-fdroid-blocked-permissions'") || !fdroidPermissionsPlugin.includes("tools:node': 'remove'")) {
  failures.push('F-Droid branch must remove legacy media-storage permissions from dependency manifests');
}
if (!env.includes('EXPO_PUBLIC_FDROID_BUILD')) {
  failures.push('Expo env helpers must expose EXPO_PUBLIC_FDROID_BUILD');
}
if (!fdroidReleasePlugin.includes('fdroidBuild') || !fdroidReleasePlugin.includes('!isFdroidBuild')) {
  failures.push('F-Droid release build plugin must make release signing conditional');
}
if (!sentryRuntime.includes('sentryEnabled = false')) {
  failures.push('Sentry runtime must be permanently disabled in the F-Droid branch');
}
if (!androidLogin.includes("Platform.OS === 'android' && !isFdroidBuild()")) {
  failures.push('Google login must be hidden in Android F-Droid builds');
}
if (!read('expo/app/_layout.tsx').includes('!isFdroidBuild()')) {
  failures.push('Expo Push notifications must be disabled in F-Droid builds');
}
if (read('expo/package.json').includes('@sentry/react-native')) {
  failures.push('F-Droid branch must not depend on @sentry/react-native');
}
if (read('expo/package.json').includes('expo-notifications')) {
  failures.push('F-Droid branch must not depend on expo-notifications');
}
if (read('expo/package.json').includes('expo-image-picker')) {
  failures.push('F-Droid branch must not depend on expo-image-picker');
}
try {
  if (read('expo/android/app/build.gradle').includes('@sentry/react-native')) {
    failures.push('F-Droid Android Gradle project must not apply Sentry');
  }
  if (!read('expo/android/app/build.gradle').includes('fdroidBuild')) {
    failures.push('F-Droid Android Gradle project must allow -PfdroidBuild release builds');
  }
} catch {
  // The native Android project is generated by expo prebuild in fdroidserver.
}
try {
  const manifest = read('expo/android/app/src/main/AndroidManifest.xml');
  if (manifest.includes('READ_EXTERNAL_STORAGE') && !manifest.includes('READ_EXTERNAL_STORAGE" tools:node="remove"')) {
    failures.push('F-Droid Android manifest must not request media storage permission');
  }
} catch {
  // The native Android project is generated by expo prebuild in fdroidserver.
}
try {
  read('expo/android/sentry.properties');
  failures.push('F-Droid Android project must not include sentry.properties');
} catch {
  // expected
}
for (const text of [
  'APP_VARIANT=fdroid',
  'EXPO_PUBLIC_FDROID_BUILD=true',
  'EXPO_PUBLIC_SENTRY_ENABLED=false',
  'Non-Free Network Services',
  'Tethered Network Services',
]) {
  if (!fdroidDocs.includes(text)) {
    failures.push(`F-Droid docs must mention ${text}`);
  }
}
if (read('fastlane/metadata/android/en-US/title.txt').trim() !== '21Life') {
  failures.push('Fastlane metadata must use the Android display name');
}
for (const text of ['NonFreeNet', `versionName: ${mobileVersion.version}`, `versionCode: ${mobileVersion.android.versionCode}`, 'app-release-unsigned.apk']) {
  if (!fdroidMetadata.includes(text)) {
    failures.push(`F-Droid metadata draft must mention ${text}`);
  }
}

if (failures.length) {
  console.error(failures.map((failure) => `- ${failure}`).join('\n'));
  process.exit(1);
}

console.log('F-Droid readiness checks passed.');
